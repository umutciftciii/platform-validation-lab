// Regenerates src/iam/auth/breached-passwords.data.ts from data/breached-passwords/ (F1-002,
// owner decision A11). Sources: the pinned SecLists file (SHA-256 checked first) and seed.txt.
// Each entry is trimmed, NFKC-normalised and lower-cased with toLowerCase(), exactly like
// isBreachedPassword; empty lines and duplicates are dropped and the result is sorted.
// The list is embedded in the API build: no file or network access at runtime. A unit test
// fails when the module is out of date.
//
//   node scripts/build-breached-passwords.mjs   (from apps/api), then Prettier
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const API_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DIR = path.join(API_DIR, "data/breached-passwords");
export const SECLISTS_FILE = "seclists-xato-net-10-million-passwords-100000.txt";
export const SECLISTS_SHA256 = "1472aafa2561df5e3293aee252aee3ca660c12b399a283cf808bb01b39be388b";

export function normalizeEntry(line) {
  return line.trim().normalize("NFKC").toLowerCase();
}

export function buildList(seclistsBytes, seedText) {
  const sha = createHash("sha256").update(seclistsBytes).digest("hex");
  if (sha !== SECLISTS_SHA256) {
    throw new Error(
      `${SECLISTS_FILE}: SHA-256 ${sha} does not match the pinned ${SECLISTS_SHA256}`,
    );
  }
  const seed = seedText.split("\n").filter((l) => !l.trim().startsWith("#"));
  const all = [...seclistsBytes.toString("utf8").split("\n"), ...seed].map(normalizeEntry);
  return [...new Set(all.filter((l) => l.length > 0))].sort();
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const entries = buildList(
    readFileSync(path.join(DIR, SECLISTS_FILE)),
    readFileSync(path.join(DIR, "seed.txt"), "utf8"),
  );
  const text = entries.join("\n");
  const out = `// Generated by scripts/build-breached-passwords.mjs from data/breached-passwords/ (SecLists,
// MIT, see data/breached-passwords/SOURCE.md, plus seed.txt). Do not edit.
export const BREACHED_PASSWORDS_COUNT = ${entries.length};
export const BREACHED_PASSWORDS_TEXT = ${JSON.stringify(text)};
`;
  writeFileSync(path.join(API_DIR, "src/iam/auth/breached-passwords.data.ts"), out);
  console.log(`${entries.length} entries`);
}
