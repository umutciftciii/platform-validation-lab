-- Global products of an archived brand are frozen (except restoring the brand first); a global
-- product never moves to another brand.
CREATE FUNCTION catalog_global_product_guard() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF TG_OP = 'UPDATE' AND NEW."brandId" IS DISTINCT FROM OLD."brandId" THEN
    RAISE EXCEPTION 'catalog: a global product cannot move to another brand'
      USING ERRCODE = 'check_violation';
  END IF;
  IF EXISTS (SELECT 1 FROM "GlobalBrand" b WHERE b."id" = NEW."brandId" AND b."status" = 'ARCHIVED') THEN
    RAISE EXCEPTION 'catalog: products of an archived brand cannot change'
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END
$fn$;
CREATE TRIGGER "GlobalProduct_guard" BEFORE INSERT OR UPDATE ON "GlobalProduct"
  FOR EACH ROW EXECUTE FUNCTION catalog_global_product_guard();

-- The cross-reference status machine, its evidence and the separation of duties.
CREATE FUNCTION catalog_cross_reference_guard() RETURNS trigger LANGUAGE plpgsql AS $fn$
DECLARE
  doc RECORD;
  content_changed BOOLEAN;
BEGIN
  IF TG_OP = 'UPDATE' AND (NEW."productId" IS DISTINCT FROM OLD."productId"
                           OR NEW."globalProductId" IS DISTINCT FROM OLD."globalProductId"
                           OR NEW."createdAt" IS DISTINCT FROM OLD."createdAt") THEN
    RAISE EXCEPTION 'catalog: the products of a cross-reference cannot change'
      USING ERRCODE = 'check_violation';
  END IF;
  IF EXISTS (SELECT 1 FROM "Product" p WHERE p."id" = NEW."productId" AND p."status" = 'ARCHIVED') THEN
    RAISE EXCEPTION 'catalog: cross-references of an archived product cannot change'
      USING ERRCODE = 'check_violation';
  END IF;
  IF TG_OP = 'INSERT' THEN
    IF NEW."status" <> 'SIMILAR' THEN
      RAISE EXCEPTION 'catalog: a cross-reference starts as SIMILAR'
        USING ERRCODE = 'check_violation';
    END IF;
    IF EXISTS (SELECT 1 FROM "GlobalProduct" g JOIN "GlobalBrand" b ON b."id" = g."brandId"
               WHERE g."id" = NEW."globalProductId" AND (g."status" = 'ARCHIVED' OR b."status" = 'ARCHIVED')) THEN
      RAISE EXCEPTION 'catalog: an archived global product cannot be cross-referenced'
        USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
  END IF;

  IF NEW."status" IS DISTINCT FROM OLD."status" AND NOT (
       (OLD."status" = 'SIMILAR' AND NEW."status" IN ('PENDING_VERIFICATION', 'REMOVED'))
    OR (OLD."status" = 'PENDING_VERIFICATION' AND NEW."status" IN ('VERIFIED', 'SIMILAR', 'REMOVED'))
    OR (OLD."status" = 'VERIFIED' AND NEW."status" IN ('PENDING_VERIFICATION', 'SIMILAR', 'REMOVED'))
    OR (OLD."status" = 'REMOVED' AND NEW."status" = 'SIMILAR')) THEN
    RAISE EXCEPTION 'catalog: cross-reference status cannot change from % to %', OLD."status", NEW."status"
      USING ERRCODE = 'check_violation';
  END IF;
  IF OLD."status" = 'REMOVED' AND NEW."status" = 'REMOVED' AND (
       NEW."description" IS DISTINCT FROM OLD."description"
       OR NEW."comparison" IS DISTINCT FROM OLD."comparison") THEN
    RAISE EXCEPTION 'catalog: a removed cross-reference cannot change'
      USING ERRCODE = 'check_violation';
  END IF;
  -- A content change voids a request or a verification: the relation is SIMILAR again.
  content_changed := NEW."description" IS DISTINCT FROM OLD."description"
                     OR NEW."comparison" IS DISTINCT FROM OLD."comparison";
  IF content_changed AND NEW."status" IN ('PENDING_VERIFICATION', 'VERIFIED') THEN
    RAISE EXCEPTION 'catalog: a changed cross-reference must be verified again'
      USING ERRCODE = 'check_violation';
  END IF;
  -- Evidence: a revision of a technical document of the same product, active, document active.
  IF NEW."status" IN ('PENDING_VERIFICATION', 'VERIFIED')
     AND (NEW."status" IS DISTINCT FROM OLD."status"
          OR NEW."sourceRevisionId" IS DISTINCT FROM OLD."sourceRevisionId") THEN
    SELECT d."productId", d."status", r."isActive" INTO doc
    FROM "ProductDocumentRevision" r JOIN "ProductDocument" d ON d."id" = r."documentId"
    WHERE r."id" = NEW."sourceRevisionId" AND d."id" = NEW."sourceDocumentId";
    IF doc."productId" IS DISTINCT FROM NEW."productId" OR doc."status" IS DISTINCT FROM 'ACTIVE'
       OR doc."isActive" IS DISTINCT FROM TRUE THEN
      RAISE EXCEPTION 'catalog: verification needs the active revision of an active document of the product'
        USING ERRCODE = 'check_violation';
    END IF;
  END IF;
  IF NEW."status" = 'VERIFIED' AND OLD."status" = 'PENDING_VERIFICATION' THEN
    IF NEW."sourceRevisionId" IS DISTINCT FROM OLD."sourceRevisionId" THEN
      RAISE EXCEPTION 'catalog: verification must confirm the requested source'
        USING ERRCODE = 'check_violation';
    END IF;
    IF NEW."verifiedById" = OLD."requestedById" OR NEW."verifiedById" = ANY (OLD."editorIds") THEN
      RAISE EXCEPTION 'catalog: separation of duties: the requester or an editor cannot verify'
        USING ERRCODE = 'insufficient_privilege';
    END IF;
  END IF;
  -- Only the PENDING -> VERIFIED step may set a verifier.
  IF NEW."verifiedById" IS NOT NULL AND NEW."verifiedById" IS DISTINCT FROM OLD."verifiedById"
     AND NOT (OLD."status" = 'PENDING_VERIFICATION' AND NEW."status" = 'VERIFIED') THEN
    RAISE EXCEPTION 'catalog: only a pending request can be verified'
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END
$fn$;
CREATE TRIGGER "ProductCrossReference_guard" BEFORE INSERT OR UPDATE ON "ProductCrossReference"
  FOR EACH ROW EXECUTE FUNCTION catalog_cross_reference_guard();

