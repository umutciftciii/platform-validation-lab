-- A site may show only a live (not removed) cross-reference of an active global product and
-- brand; a pending request is still shown as SIMILAR, a stale verification is filtered by the
-- public route. Site rows are added and removed, never changed.
CREATE FUNCTION catalog_cross_reference_site_guard() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF TG_OP = 'UPDATE' THEN
    RAISE EXCEPTION 'catalog: a cross-reference site row cannot change; remove and add it'
      USING ERRCODE = 'check_violation';
  END IF;
  IF NOT EXISTS (
       SELECT 1 FROM "ProductCrossReference" x
       JOIN "GlobalProduct" g ON g."id" = x."globalProductId"
       JOIN "GlobalBrand" b ON b."id" = g."brandId"
       WHERE x."id" = NEW."crossReferenceId" AND x."status" IN ('SIMILAR', 'PENDING_VERIFICATION', 'VERIFIED')
         AND g."status" = 'ACTIVE' AND b."status" = 'ACTIVE') THEN
    RAISE EXCEPTION 'catalog: only a live cross-reference of an active global product can be shown on a site'
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END
$fn$;
CREATE TRIGGER "ProductCrossReferenceSite_guard" BEFORE INSERT OR UPDATE ON "ProductCrossReferenceSite"
  FOR EACH ROW EXECUTE FUNCTION catalog_cross_reference_site_guard();

