-- ML-1 (DP-073, ADR-028 D2): the languages of each site.
--
-- Runs as dp_owner (ADR-012A). Additive only: one table, its CHECK constraints, one partial
-- unique index, three functions with their triggers, and the seed rows of the existing sites.
-- No existing table, column, row, role, policy or trigger changes; the CMS page and revision
-- tables are untouched.
--
--  * "SiteLocale": one row per (site, language). `enabled` opens a language for editing in the
--    admin, `public` makes it visible on the site, `isDefault` marks the site's default language.
--    Like "Site" and the CMS tables it is configuration, not customer data: no row-level
--    security (ADR-020 D5); request code reaches it through the site-scoped client.
--  * Rules: a valid BCP 47 tag (same rule as "Site"."defaultLocale"); public implies enabled; the
--    default is enabled and public; at most one default per site (partial unique index); and at
--    the end of every transaction each site has exactly one default, equal to
--    "Site"."defaultLocale" (deferred constraint triggers on both tables).
--  * A new site gets its default row in the same statement (trigger on "Site"); further
--    languages come from the catalogue sync (insert only, never an update) or a migration.
--  * dp_app may only read the table. Switching a language public is not part of ML-1: a later,
--    separately approved change adds an audited path for it (ADR-028 D14).
--
-- Seed (owner brief ML-1): every existing site gets its current default language (enabled,
-- public, default); BV also gets "nl" (enabled, not public). Corporate keeps only its default.
--
-- Part 1 is generated by `prisma migrate diff --from-schema <main> --to-schema schema.prisma`.
-- Part 2 adds the rules Prisma cannot model; test/integration/cms.int.test.ts (section 21)
-- covers each one, including the rollback below.
--
-- Rollback (nothing refers to the table yet; no other data is lost):
--   DROP TRIGGER "Site_default_locale_row" ON "Site";
--   DROP TRIGGER "Site_default_locale_consistent" ON "Site";
--   DROP TABLE "SiteLocale";
--   DROP FUNCTION site_locale_default_row(), site_locale_check_site(uuid), site_locale_consistent();

-- ===========================================================================================
-- Part 0: preconditions
-- ===========================================================================================

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'dp_app') THEN
    RAISE EXCEPTION 'ML-1: role dp_app missing; ADR-012A must be applied first';
  END IF;
  IF EXISTS (
    SELECT 1 FROM "Site" WHERE "defaultLocale" !~ '^[a-z]{2,3}(-[A-Za-z0-9]{2,8})*$'
  ) THEN
    RAISE EXCEPTION 'ML-1: a site has an invalid default locale';
  END IF;
END $$;

-- ===========================================================================================
-- Part 1: table and indexes (generated)
-- ===========================================================================================

-- CreateTable
CREATE TABLE "SiteLocale" (
    "siteId" UUID NOT NULL,
    "locale" VARCHAR(35) NOT NULL,
    "enabled" BOOLEAN NOT NULL DEFAULT false,
    "public" BOOLEAN NOT NULL DEFAULT false,
    "isDefault" BOOLEAN NOT NULL DEFAULT false,
    "sortOrder" INTEGER NOT NULL DEFAULT 0,
    "createdAt" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updatedAt" TIMESTAMPTZ(3) NOT NULL,

    CONSTRAINT "SiteLocale_pkey" PRIMARY KEY ("siteId","locale")
);

-- CreateIndex
CREATE UNIQUE INDEX "SiteLocale_default_siteId_key" ON "SiteLocale"("siteId") WHERE ("isDefault");

-- AddForeignKey
ALTER TABLE "SiteLocale" ADD CONSTRAINT "SiteLocale_siteId_fkey" FOREIGN KEY ("siteId") REFERENCES "Site"("id") ON DELETE RESTRICT ON UPDATE CASCADE;

-- ===========================================================================================
-- Part 2: consistency (CHECK, triggers)
-- ===========================================================================================

ALTER TABLE "SiteLocale"
  ADD CONSTRAINT "SiteLocale_locale_format"
    CHECK ("locale" ~ '^[a-z]{2,3}(-[A-Za-z0-9]{2,8})*$'),
  ADD CONSTRAINT "SiteLocale_public_enabled" CHECK (NOT "public" OR "enabled"),
  ADD CONSTRAINT "SiteLocale_default_public" CHECK (NOT "isDefault" OR ("enabled" AND "public")),
  ADD CONSTRAINT "SiteLocale_sort_order" CHECK ("sortOrder" BETWEEN 0 AND 1000);

-- Exactly one default per site, equal to "Site"."defaultLocale". Checked at commit, so a change
-- of the default (old row off, new row on, site column) can happen in one transaction.
CREATE FUNCTION site_locale_check_site(site_id uuid) RETURNS void
LANGUAGE plpgsql AS $$
DECLARE
  site_default text;
  defaults integer;
  default_locale text;
BEGIN
  SELECT s."defaultLocale" INTO site_default FROM "Site" s WHERE s."id" = site_id;
  IF NOT FOUND THEN
    RETURN;
  END IF;
  SELECT count(*), min(l."locale") INTO defaults, default_locale
  FROM "SiteLocale" l WHERE l."siteId" = site_id AND l."isDefault";
  IF defaults <> 1 THEN
    RAISE EXCEPTION 'site locale: a site needs exactly one default language (SiteLocale_one_default)';
  END IF;
  IF default_locale <> site_default THEN
    RAISE EXCEPTION 'site locale: the default language differs from Site.defaultLocale (SiteLocale_matches_site)';
  END IF;
END $$;

CREATE FUNCTION site_locale_consistent() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_TABLE_NAME = 'Site' THEN
    PERFORM site_locale_check_site(NEW."id");
  ELSE
    IF TG_OP IN ('UPDATE', 'DELETE') THEN
      PERFORM site_locale_check_site(OLD."siteId");
    END IF;
    IF TG_OP IN ('INSERT', 'UPDATE') THEN
      PERFORM site_locale_check_site(NEW."siteId");
    END IF;
  END IF;
  RETURN NULL;
END $$;

CREATE CONSTRAINT TRIGGER "SiteLocale_consistent"
  AFTER INSERT OR UPDATE OR DELETE ON "SiteLocale"
  DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION site_locale_consistent();

CREATE CONSTRAINT TRIGGER "Site_default_locale_consistent"
  AFTER INSERT OR UPDATE OF "defaultLocale" ON "Site"
  DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION site_locale_consistent();

-- A new site gets its default language row in the same statement. SECURITY DEFINER: the row is
-- written as the table owner whoever creates the site (only the catalogue sync does, as dp_owner).
CREATE FUNCTION site_locale_default_row() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
BEGIN
  INSERT INTO "SiteLocale" ("siteId", "locale", "enabled", "public", "isDefault", "sortOrder", "updatedAt")
  VALUES (NEW."id", NEW."defaultLocale", true, true, true, 0, CURRENT_TIMESTAMP)
  ON CONFLICT ("siteId", "locale") DO NOTHING;
  RETURN NULL;
END $$;

-- Trigger functions only: nobody calls them directly (no PUBLIC EXECUTE, as in DP-103/DP-125).
REVOKE ALL ON FUNCTION site_locale_default_row() FROM PUBLIC;
REVOKE ALL ON FUNCTION site_locale_consistent() FROM PUBLIC;
REVOKE ALL ON FUNCTION site_locale_check_site(uuid) FROM PUBLIC;

CREATE TRIGGER "Site_default_locale_row"
  AFTER INSERT ON "Site"
  FOR EACH ROW EXECUTE FUNCTION site_locale_default_row();

-- ===========================================================================================
-- Part 3: seed of the existing sites
-- ===========================================================================================

INSERT INTO "SiteLocale" ("siteId", "locale", "enabled", "public", "isDefault", "sortOrder", "updatedAt")
SELECT "id", "defaultLocale", true, true, true, 0, CURRENT_TIMESTAMP FROM "Site";

INSERT INTO "SiteLocale" ("siteId", "locale", "enabled", "public", "isDefault", "sortOrder", "updatedAt")
SELECT "id", 'nl', true, false, false, 10, CURRENT_TIMESTAMP FROM "Site"
WHERE "key" = 'BV' AND "defaultLocale" <> 'nl';

-- ===========================================================================================
-- Part 4: privileges (ADR-012A default privileges gave dp_app full DML on the new table)
-- ===========================================================================================

-- The API reads the languages; it never changes them in ML-1.
REVOKE INSERT, UPDATE, DELETE ON TABLE "SiteLocale" FROM dp_app;
