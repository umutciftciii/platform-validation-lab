ALTER TABLE "SiteRedirect"
  -- A path of the site: starts with one "/", no "//", no query or fragment, not the home page,
  -- never the app's internals. Upper case and dots are allowed for legacy addresses (DP-212).
  ADD CONSTRAINT "SiteRedirect_source_path" CHECK (
    "sourcePath" ~ '^/[A-Za-z0-9._~!$&''()*+,;=:@%/-]+$'
    AND "sourcePath" !~ '//'
    AND "sourcePath" !~ '^/(_next|api)(/|$)'
  ),
  ADD CONSTRAINT "SiteRedirect_source_query" CHECK (
    "sourceQuery" = '' OR "sourceQuery" ~ '^[A-Za-z0-9._~%=&+-]+$'
  ),
  -- A path of the same site (optionally with a query) or an https URL.
  ADD CONSTRAINT "SiteRedirect_target" CHECK (
    (
      "target" ~ '^/([A-Za-z0-9._~!$&''()*+,;=:@%/-]*)(\?[A-Za-z0-9._~%=&+-]*)?$'
      AND "target" !~ '//'
      AND "target" !~ '^/(_next|api)(/|\?|$)'
    )
    OR "target" ~ '^https://[A-Za-z0-9.-]+(:[0-9]{1,5})?(/[^[:space:]]*)?$'
  ),
  ADD CONSTRAINT "SiteRedirect_not_self" CHECK (
    "sourceQuery" <> '' OR split_part("target", '?', 1) <> "sourcePath"
  ),
  ADD CONSTRAINT "SiteRedirect_status_code" CHECK ("statusCode" IN (301, 302)),
  -- A slug change is a permanent move of one page or product, for every query string.
  ADD CONSTRAINT "SiteRedirect_slug_change" CHECK (
    ("origin" = 'SLUG_CHANGE') = ("contentType" IS NOT NULL)
    AND ("contentType" IS NULL) = ("contentId" IS NULL)
    AND ("origin" <> 'SLUG_CHANGE' OR ("statusCode" = 301 AND "sourceQuery" = ''))
  ),
  ADD CONSTRAINT "SiteRedirect_note_trimmed" CHECK (
    "note" IS NULL OR ("note" = btrim("note") AND length("note") >= 1)
  ),
  ADD CONSTRAINT "SiteRedirect_version_positive" CHECK ("version" >= 1);

