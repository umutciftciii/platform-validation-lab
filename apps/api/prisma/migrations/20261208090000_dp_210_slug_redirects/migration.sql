-- No chain (and so no loop) among the ACTIVE redirects of a site. A redirect whose source carries
-- a query only applies with that query, so only plain sources (sourceQuery '') take part.
CREATE FUNCTION site_redirect_no_chain() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  target_path text;
BEGIN
  IF NOT NEW."active" THEN
    RETURN NEW;
  END IF;
  IF left(NEW."target", 1) = '/' THEN
    target_path := split_part(NEW."target", '?', 1);
    IF EXISTS (
      SELECT 1 FROM "SiteRedirect" r
      WHERE r."siteId" = NEW."siteId" AND r."id" <> NEW."id" AND r."active"
        AND r."sourceQuery" = '' AND r."sourcePath" = target_path
    ) THEN
      RAISE EXCEPTION 'seo: a redirect target cannot be the source of another redirect (chain)';
    END IF;
  END IF;
  IF NEW."sourceQuery" = '' AND EXISTS (
    SELECT 1 FROM "SiteRedirect" r
    WHERE r."siteId" = NEW."siteId" AND r."id" <> NEW."id" AND r."active"
      AND left(r."target", 1) = '/' AND split_part(r."target", '?', 1) = NEW."sourcePath"
  ) THEN
    RAISE EXCEPTION 'seo: a redirect source cannot be the target of another redirect (chain)';
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER "SiteRedirect_no_chain"
  BEFORE INSERT OR UPDATE ON "SiteRedirect"
  FOR EACH ROW EXECUTE FUNCTION site_redirect_no_chain();

-- One lock row per existing site; the API creates the row of a later site on first use (an
-- upsert, so two first uses wait for each other too).
INSERT INTO "SitePathLock" ("siteId", "updatedAt")
SELECT "id", CURRENT_TIMESTAMP FROM "Site"
ON CONFLICT ("siteId") DO NOTHING;

