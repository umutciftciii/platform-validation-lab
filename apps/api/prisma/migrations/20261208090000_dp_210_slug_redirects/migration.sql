-- DP-210 (ADR-024 D7/D8): slug changes keep the old address (automatic 301), and the redirect
-- table DP-211 will manage.
--
-- Runs as dp_owner (ADR-012A). Additive only: two enums, two tables, CHECK constraints, one guard
-- trigger and one row per existing site in "SitePathLock". No existing table, row, role, grant,
-- policy, function or trigger changes. Both tables are site-bound in the site-scoped client
-- (site-scope.ts) and have no row-level security (like the CMS and catalogue tables, ADR-020 D5).
--
--  * "SiteRedirect": an old address of a site and where it goes. The API writes SLUG_CHANGE rows
--    in the transaction that publishes a page, article or product at a new address; MANUAL and
--    IMPORT rows (and the admin screens) arrive with DP-211/DP-212, on the same columns.
--  * No chain, no loop: the target of an ACTIVE redirect is never the source of another ACTIVE
--    redirect of the site (trigger). With source <> target that also excludes every loop. The API
--    keeps it so by pointing older redirects at the newest address (A -> B, then B -> C makes
--    A -> C and B -> C) and by switching a redirect off when live content takes its source again.
--  * "SitePathLock": every transaction that changes a site's live addresses updates the site's row
--    first, so concurrent publications see each other's addresses and redirects (the trigger reads
--    committed rows only; the lock makes the read complete).
--
-- Part 1 is generated by `prisma migrate diff --from-schema <main> --to-schema schema.prisma`.
-- Part 2 adds the rules Prisma cannot model; test/integration/seo-redirects.int.test.ts covers
-- each one.
--
-- Rollback: roll forward. Dropping both tables loses only redirects (old addresses become 404
-- again, the DP-207 behaviour); no other data refers to them.

