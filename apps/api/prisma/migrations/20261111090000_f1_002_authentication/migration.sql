-- 2.7 Immutability (design 8.3): consumedAt, invalidatedAt, usedAt and revokedAt are set once and
-- never return to NULL or change; the identity of a token, code, factor or session is fixed; the
-- failure counter of a token and the TOTP replay step never go back.

CREATE FUNCTION iam_credential_token_immutable() RETURNS trigger LANGUAGE plpgsql
SET search_path = pg_catalog, public, pg_temp AS $fn$
BEGIN
  IF (OLD."consumedAt" IS NOT NULL AND NEW."consumedAt" IS DISTINCT FROM OLD."consumedAt")
     OR (OLD."invalidatedAt" IS NOT NULL AND NEW."invalidatedAt" IS DISTINCT FROM OLD."invalidatedAt") THEN
    RAISE EXCEPTION 'iam: consumedAt and invalidatedAt are set once' USING ERRCODE = 'check_violation';
  END IF;
  IF NEW."failedAttempts" < OLD."failedAttempts" THEN
    RAISE EXCEPTION 'iam: failedAttempts never decreases' USING ERRCODE = 'check_violation';
  END IF;
  IF NEW."userId" IS DISTINCT FROM OLD."userId" OR NEW."purpose" IS DISTINCT FROM OLD."purpose"
     OR NEW."tokenHash" IS DISTINCT FROM OLD."tokenHash"
     OR NEW."securityVersion" IS DISTINCT FROM OLD."securityVersion"
     OR NEW."app" IS DISTINCT FROM OLD."app" OR NEW."siteId" IS DISTINCT FROM OLD."siteId"
     OR NEW."newEmail" IS DISTINCT FROM OLD."newEmail"
     OR NEW."expiresAt" IS DISTINCT FROM OLD."expiresAt"
     OR NEW."createdByType" IS DISTINCT FROM OLD."createdByType"
     OR NEW."createdByUserId" IS DISTINCT FROM OLD."createdByUserId"
     OR NEW."createdAt" IS DISTINCT FROM OLD."createdAt" THEN
    RAISE EXCEPTION 'iam: a credential token is immutable except consumedAt, invalidatedAt and failedAttempts'
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END
$fn$;
CREATE TRIGGER "UserCredentialToken_immutable" BEFORE UPDATE ON "UserCredentialToken"
  FOR EACH ROW EXECUTE FUNCTION iam_credential_token_immutable();

CREATE FUNCTION iam_recovery_code_immutable() RETURNS trigger LANGUAGE plpgsql
SET search_path = pg_catalog, public, pg_temp AS $fn$
BEGIN
  IF OLD."usedAt" IS NOT NULL AND NEW."usedAt" IS DISTINCT FROM OLD."usedAt" THEN
    RAISE EXCEPTION 'iam: usedAt is set once' USING ERRCODE = 'check_violation';
  END IF;
  IF NEW."userId" IS DISTINCT FROM OLD."userId" OR NEW."codeHash" IS DISTINCT FROM OLD."codeHash"
     OR NEW."createdAt" IS DISTINCT FROM OLD."createdAt" THEN
    RAISE EXCEPTION 'iam: a recovery code is immutable except usedAt' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END
$fn$;
CREATE TRIGGER "MfaRecoveryCode_immutable" BEFORE UPDATE ON "MfaRecoveryCode"
  FOR EACH ROW EXECUTE FUNCTION iam_recovery_code_immutable();

CREATE FUNCTION iam_mfa_factor_immutable() RETURNS trigger LANGUAGE plpgsql
SET search_path = pg_catalog, public, pg_temp AS $fn$
BEGIN
  IF OLD."confirmedAt" IS NOT NULL AND NEW."confirmedAt" IS DISTINCT FROM OLD."confirmedAt" THEN
    RAISE EXCEPTION 'iam: confirmedAt is set once' USING ERRCODE = 'check_violation';
  END IF;
  IF OLD."lastUsedStep" IS NOT NULL
     AND (NEW."lastUsedStep" IS NULL OR NEW."lastUsedStep" < OLD."lastUsedStep") THEN
    RAISE EXCEPTION 'iam: lastUsedStep never goes back (TOTP replay guard)' USING ERRCODE = 'check_violation';
  END IF;
  IF NEW."userId" IS DISTINCT FROM OLD."userId" OR NEW."type" IS DISTINCT FROM OLD."type"
     OR NEW."createdAt" IS DISTINCT FROM OLD."createdAt" THEN
    RAISE EXCEPTION 'iam: the owner and type of an MFA factor are immutable' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END
$fn$;
CREATE TRIGGER "MfaFactor_immutable" BEFORE UPDATE ON "MfaFactor"
  FOR EACH ROW EXECUTE FUNCTION iam_mfa_factor_immutable();

-- rotatedFromId may only become NULL (ON DELETE SET NULL when the cleanup removes the parent).
CREATE FUNCTION iam_session_immutable() RETURNS trigger LANGUAGE plpgsql
SET search_path = pg_catalog, public, pg_temp AS $fn$
BEGIN
  IF (OLD."revokedAt" IS NOT NULL AND NEW."revokedAt" IS DISTINCT FROM OLD."revokedAt")
     OR (OLD."revokedReason" IS NOT NULL AND NEW."revokedReason" IS DISTINCT FROM OLD."revokedReason") THEN
    RAISE EXCEPTION 'iam: revokedAt and revokedReason are set once' USING ERRCODE = 'check_violation';
  END IF;
  IF NEW."tokenHash" IS DISTINCT FROM OLD."tokenHash" OR NEW."userId" IS DISTINCT FROM OLD."userId"
     OR NEW."kind" IS DISTINCT FROM OLD."kind" OR NEW."app" IS DISTINCT FROM OLD."app"
     OR NEW."siteId" IS DISTINCT FROM OLD."siteId"
     OR NEW."securityVersion" IS DISTINCT FROM OLD."securityVersion"
     OR NEW."createdAt" IS DISTINCT FROM OLD."createdAt"
     OR NEW."absoluteExpiresAt" IS DISTINCT FROM OLD."absoluteExpiresAt"
     OR NEW."persistent" IS DISTINCT FROM OLD."persistent"
     OR (NEW."rotatedFromId" IS DISTINCT FROM OLD."rotatedFromId" AND NEW."rotatedFromId" IS NOT NULL) THEN
    RAISE EXCEPTION 'iam: the identity, owner and absolute expiry of a session are immutable'
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END
$fn$;
CREATE TRIGGER "Session_immutable" BEFORE UPDATE ON "Session"
  FOR EACH ROW EXECUTE FUNCTION iam_session_immutable();

-- 2.8 K-NG3: database-generated audit (AFTER triggers, same transaction). Meaningful because
-- dp_app owns nothing and may only SELECT/INSERT AuditEvent (ADR-012A): a compromised API can
-- write a forged assignment or session, but cannot remove this trace.

CREATE FUNCTION iam_role_assignment_db_audit() RETURNS trigger LANGUAGE plpgsql
SET search_path = pg_catalog, public, pg_temp AS $fn$
DECLARE
  r "RoleAssignment";
  role_key text;
  changed text[] := ARRAY[]::text[];
BEGIN
  IF TG_OP = 'DELETE' THEN
    r := OLD;
  ELSE
    r := NEW;
  END IF;
  IF TG_OP = 'UPDATE' THEN
    IF NEW."revokedAt" IS DISTINCT FROM OLD."revokedAt" THEN changed := array_append(changed, 'revokedAt'); END IF;
    IF NEW."expiresAt" IS DISTINCT FROM OLD."expiresAt" THEN changed := array_append(changed, 'expiresAt'); END IF;
    IF cardinality(changed) = 0 THEN
      RETURN NULL;
    END IF;
  END IF;
  SELECT ro."key" INTO role_key FROM "Role" ro WHERE ro."id" = r."roleId";
  PERFORM iam_db_audit(
    CASE WHEN TG_OP = 'INSERT' THEN 'db.role_assignment_created' ELSE 'db.role_assignment_changed' END,
    'role_assignment', r."id"::text, r."scopeType", r."siteId",
    jsonb_strip_nulls(jsonb_build_object(
      'operation', lower(TG_OP),
      'userId', r."userId",
      'role', role_key,
      'changed', CASE WHEN TG_OP = 'UPDATE' THEN to_jsonb(changed) END,
      'claimedActor', CASE WHEN TG_OP = 'INSERT' THEN r."grantedById" ELSE r."revokedById" END,
      'nullGrantor', CASE WHEN TG_OP = 'INSERT' THEN r."grantedById" IS NULL END)));
  RETURN NULL;
END
$fn$;
CREATE TRIGGER "RoleAssignment_db_audit" AFTER INSERT OR UPDATE OR DELETE ON "RoleAssignment"
  FOR EACH ROW EXECUTE FUNCTION iam_role_assignment_db_audit();

CREATE FUNCTION iam_user_security_db_audit() RETURNS trigger LANGUAGE plpgsql
SET search_path = pg_catalog, public, pg_temp AS $fn$
DECLARE
  changed text[] := ARRAY[]::text[];
BEGIN
  IF NEW."status" IS DISTINCT FROM OLD."status" THEN changed := array_append(changed, 'status'); END IF;
  IF NEW."passwordHash" IS DISTINCT FROM OLD."passwordHash" THEN changed := array_append(changed, 'passwordHash'); END IF;
  IF NEW."mfaEnrolledAt" IS DISTINCT FROM OLD."mfaEnrolledAt" THEN changed := array_append(changed, 'mfaEnrolledAt'); END IF;
  IF NEW."emailNormalized" IS DISTINCT FROM OLD."emailNormalized" THEN changed := array_append(changed, 'emailNormalized'); END IF;
  IF NEW."securityVersion" IS DISTINCT FROM OLD."securityVersion" THEN changed := array_append(changed, 'securityVersion'); END IF;
  IF cardinality(changed) > 0 THEN
    PERFORM iam_db_audit('db.user_security_changed', 'user', NEW."id"::text, 'PLATFORM', NULL,
      jsonb_build_object('userId', NEW."id", 'kind', NEW."kind", 'changed', to_jsonb(changed)));
  END IF;
  RETURN NULL;
END
$fn$;
CREATE TRIGGER "User_security_db_audit" AFTER UPDATE ON "User"
  FOR EACH ROW EXECUTE FUNCTION iam_user_security_db_audit();

