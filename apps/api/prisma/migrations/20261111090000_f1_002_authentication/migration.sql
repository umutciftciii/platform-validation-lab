-- 2.6 Site and kind consistency of sessions and tokens (design 8.2).

CREATE FUNCTION iam_session_site_guard() RETURNS trigger LANGUAGE plpgsql
SET search_path = pg_catalog, public, pg_temp AS $fn$
DECLARE
  user_kind "UserKind";
  site_key "SiteKey";
BEGIN
  SELECT u."kind" INTO user_kind FROM "User" u WHERE u."id" = NEW."userId";
  IF user_kind IS DISTINCT FROM NEW."kind" THEN
    RAISE EXCEPTION 'iam: Session.kind must equal the user''s kind' USING ERRCODE = 'check_violation';
  END IF;
  IF NEW."siteId" IS NOT NULL THEN
    SELECT s."key" INTO site_key FROM "Site" s WHERE s."id" = NEW."siteId";
    IF (NEW."app" = 'WEB_BV' AND site_key IS DISTINCT FROM 'BV')
       OR (NEW."app" = 'WEB_CORPORATE' AND site_key IS DISTINCT FROM 'CORPORATE') THEN
      RAISE EXCEPTION 'iam: the session app does not match its site' USING ERRCODE = 'check_violation';
    END IF;
  END IF;
  RETURN NEW;
END
$fn$;
CREATE TRIGGER "Session_site_guard" BEFORE INSERT OR UPDATE ON "Session"
  FOR EACH ROW EXECUTE FUNCTION iam_session_site_guard();

