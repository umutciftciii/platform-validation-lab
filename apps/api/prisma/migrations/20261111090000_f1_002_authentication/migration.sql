-- 2.3 Helpers.

-- Time-ordered UUID (version 7) for rows the database writes itself. PostgreSQL 17 has no
-- uuidv7(); this sets the 48-bit millisecond timestamp and the version bits on a random UUID.
CREATE FUNCTION iam_uuid_v7() RETURNS uuid LANGUAGE sql VOLATILE
SET search_path = pg_catalog AS $fn$
  SELECT encode(
    set_bit(set_bit(
      overlay(uuid_send(gen_random_uuid())
              PLACING substring(int8send(floor(extract(epoch FROM clock_timestamp()) * 1000)::bigint) FROM 3)
              FROM 1 FOR 6),
      52, 1), 53, 1),
    'hex')::uuid
$fn$;

-- K-NG3: database-generated audit events. SECURITY INVOKER on purpose: `dbUser` is the role that
-- wrote the row (ADR-012A gives each component its own role), which is the only actor evidence
-- the database has. `claimedActor` is what the writer claimed (grantor, revoker, session owner).
-- Values of changed fields are never recorded, only their names.
CREATE FUNCTION iam_db_audit(
  p_action text, p_resource_type text, p_resource_id text, p_scope "ScopeType", p_site uuid,
  p_metadata jsonb
) RETURNS void LANGUAGE plpgsql SECURITY INVOKER
SET search_path = pg_catalog, public, pg_temp AS $fn$
BEGIN
  INSERT INTO "AuditEvent"
    ("id", "actorType", "action", "resourceType", "resourceId", "scopeType", "siteId", "outcome", "metadata")
  VALUES
    (iam_uuid_v7(), 'SYSTEM', p_action, p_resource_type, p_resource_id, p_scope, p_site, 'SUCCESS',
     coalesce(p_metadata, '{}'::jsonb)
       || jsonb_build_object('dbUser', current_user::text, 'source', 'database_trigger'));
END
$fn$;

-- db.* events can only come from these triggers: an INSERT of a db.* action at trigger depth 1
-- (a direct statement, or iam_db_audit called directly) is refused, so the API cannot forge a
-- database-generated event. Only migrations (dp_owner) can create triggers.
CREATE FUNCTION iam_audit_event_db_action_guard() RETURNS trigger LANGUAGE plpgsql
SET search_path = pg_catalog, public, pg_temp AS $fn$
BEGIN
  IF NEW."action" LIKE 'db.%' AND pg_trigger_depth() < 2 THEN
    RAISE EXCEPTION 'iam: db.* audit events are written only by database triggers (K-NG3)'
      USING ERRCODE = 'insufficient_privilege';
  END IF;
  RETURN NEW;
END
$fn$;
CREATE TRIGGER "AuditEvent_db_action_guard" BEFORE INSERT ON "AuditEvent"
  FOR EACH ROW EXECUTE FUNCTION iam_audit_event_db_action_guard();

-- 2.4 K-NG1 and K-NG2: who may write a role assignment without, or with, a grantor.

-- pg_advisory_xact_lock key 20619473380659028 = "IAMBOOT" in ASCII, the bootstrap's own lock
-- (src/iam/bootstrap.ts BOOTSTRAP_LOCK_KEY), so this check and the bootstrap are serialised.
CREATE FUNCTION iam_null_grantor_guard() RETURNS trigger LANGUAGE plpgsql
SET search_path = pg_catalog, public, pg_temp AS $fn$
DECLARE
  role_key text;
  target record;
BEGIN
  IF NEW."grantedById" IS NOT NULL THEN
    -- The bootstrap credential writes only the bootstrap row: it cannot attribute a grant to an
    -- existing administrator (T14: the credential is useless once an administrator exists).
    IF current_user = 'dp_iam_bootstrap' THEN
      RAISE EXCEPTION 'iam: dp_iam_bootstrap may only write the bootstrap assignment (no grantor)'
        USING ERRCODE = 'insufficient_privilege';
    END IF;
    RETURN NEW;
  END IF;
  -- Actor evidence: the connection's database role (ADR-012A). Row conditions alone would not
  -- prove who wrote the row (design 9.2).
  IF current_user <> 'dp_iam_bootstrap' THEN
    RAISE EXCEPTION 'iam: a role assignment without grantor is allowed only for the bootstrap, as dp_iam_bootstrap (K-NG1)'
      USING ERRCODE = 'insufficient_privilege';
  END IF;
  SELECT r."key" INTO role_key FROM "Role" r WHERE r."id" = NEW."roleId";
  IF role_key IS DISTINCT FROM 'platform_super_admin' OR NEW."scopeType" <> 'PLATFORM'
     OR NEW."siteId" IS NOT NULL OR NEW."expiresAt" IS NOT NULL OR NEW."revokedAt" IS NOT NULL
     OR NEW."reason" IS NULL THEN
    RAISE EXCEPTION 'iam: the bootstrap may only assign platform_super_admin at PLATFORM scope, without expiry and with a reason (K-NG1)'
      USING ERRCODE = 'insufficient_privilege';
  END IF;
  SELECT u."kind", u."status", u."passwordHash", u."mfaEnrolledAt" INTO target
  FROM "User" u WHERE u."id" = NEW."userId";
  IF NOT FOUND OR target."kind" <> 'STAFF' OR target."status" <> 'PENDING'
     OR target."passwordHash" IS NOT NULL OR target."mfaEnrolledAt" IS NOT NULL THEN
    RAISE EXCEPTION 'iam: the bootstrap target must be a PENDING staff user without password or MFA (K-NG1)'
      USING ERRCODE = 'insufficient_privilege';
  END IF;
  PERFORM pg_advisory_xact_lock(20619473380659028);
  IF iam_platform_admins_remaining(NULL, NULL) > 0 THEN
    RAISE EXCEPTION 'iam: bootstrap refused, a platform administrator already exists (K-NG1)'
      USING ERRCODE = 'insufficient_privilege';
  END IF;
  RETURN NEW;
END
$fn$;
CREATE TRIGGER "RoleAssignment_null_grantor_guard" BEFORE INSERT ON "RoleAssignment"
  FOR EACH ROW EXECUTE FUNCTION iam_null_grantor_guard();

-- K-NG2: a named grantor is an ACTIVE staff user with MFA. A consistency guard, not actor
-- evidence (design 9.2-3). Checked when the grant is written; revoking later is never blocked.
CREATE FUNCTION iam_grantor_guard() RETURNS trigger LANGUAGE plpgsql
SET search_path = pg_catalog, public, pg_temp AS $fn$
BEGIN
  IF NEW."grantedById" IS NOT NULL AND NOT EXISTS (
       SELECT 1 FROM "User" g
       WHERE g."id" = NEW."grantedById" AND g."kind" = 'STAFF' AND g."status" = 'ACTIVE'
         AND g."mfaEnrolledAt" IS NOT NULL) THEN
    RAISE EXCEPTION 'iam: the grantor must be an ACTIVE staff user with MFA (K-NG2)'
      USING ERRCODE = 'insufficient_privilege';
  END IF;
  RETURN NEW;
END
$fn$;
CREATE TRIGGER "RoleAssignment_grantor_guard" BEFORE INSERT ON "RoleAssignment"
  FOR EACH ROW EXECUTE FUNCTION iam_grantor_guard();

