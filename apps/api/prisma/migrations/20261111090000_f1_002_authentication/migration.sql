-- Confirmation and removal of a factor.
CREATE FUNCTION iam_mfa_factor_db_audit() RETURNS trigger LANGUAGE plpgsql
SET search_path = pg_catalog, public, pg_temp AS $fn$
DECLARE
  f "MfaFactor";
BEGIN
  IF TG_OP = 'UPDATE' AND NOT (OLD."confirmedAt" IS NULL AND NEW."confirmedAt" IS NOT NULL) THEN
    RETURN NULL;
  END IF;
  IF TG_OP = 'DELETE' THEN
    f := OLD;
  ELSE
    f := NEW;
  END IF;
  PERFORM iam_db_audit('db.mfa_factor_changed', 'mfa_factor', f."id"::text, 'PLATFORM', NULL,
    jsonb_build_object('userId', f."userId", 'type', f."type",
      'change', CASE WHEN TG_OP = 'DELETE' THEN 'deleted' ELSE 'confirmed' END,
      'wasConfirmed', TG_OP = 'DELETE' AND f."confirmedAt" IS NOT NULL));
  RETURN NULL;
END
$fn$;
CREATE TRIGGER "MfaFactor_db_audit" AFTER UPDATE OF "confirmedAt" OR DELETE ON "MfaFactor"
  FOR EACH ROW EXECUTE FUNCTION iam_mfa_factor_db_audit();
