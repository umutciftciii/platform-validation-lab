CREATE TRIGGER "ProductReviewEvent_no_truncate" BEFORE TRUNCATE ON "ProductReviewEvent"
  FOR EACH STATEMENT EXECUTE FUNCTION catalog_review_event_append_only();

-- A publication goes live only with approved content: whenever a row becomes PUBLISHED or its
-- snapshot is replaced, the master must be APPROVED in exactly the published version and the
-- listing VISIBLE in exactly the published listing version. Product, site and listing never
-- change; the snapshot changes only together with a new publishedAt (republishing).
CREATE FUNCTION catalog_publication_guard() RETURNS trigger LANGUAGE plpgsql AS $fn$
DECLARE
  p RECORD;
  l RECORD;
BEGIN
  IF TG_OP = 'UPDATE' THEN
    IF NEW."productId" IS DISTINCT FROM OLD."productId"
       OR NEW."siteId" IS DISTINCT FROM OLD."siteId"
       OR NEW."listingId" IS DISTINCT FROM OLD."listingId" THEN
      RAISE EXCEPTION 'catalog: the product, site and listing of a publication cannot change'
        USING ERRCODE = 'check_violation';
    END IF;
    IF (NEW."snapshot" IS DISTINCT FROM OLD."snapshot"
        OR NEW."productVersion" IS DISTINCT FROM OLD."productVersion"
        OR NEW."listingVersion" IS DISTINCT FROM OLD."listingVersion"
        OR NEW."imageIds" IS DISTINCT FROM OLD."imageIds")
       AND NEW."publishedAt" IS NOT DISTINCT FROM OLD."publishedAt" THEN
      RAISE EXCEPTION 'catalog: a published snapshot is replaced only by publishing again'
        USING ERRCODE = 'check_violation';
    END IF;
  END IF;
  IF NEW."status" = 'PUBLISHED' AND (
       TG_OP = 'INSERT' OR OLD."status" <> 'PUBLISHED'
       OR NEW."publishedAt" IS DISTINCT FROM OLD."publishedAt") THEN
    SELECT "status", "version", "approvedVersion" INTO p FROM "Product" WHERE "id" = NEW."productId";
    IF p."status" IS DISTINCT FROM 'APPROVED'
       OR p."version" IS DISTINCT FROM NEW."productVersion"
       OR p."approvedVersion" IS DISTINCT FROM NEW."productVersion" THEN
      RAISE EXCEPTION 'catalog: only the approved version of a product can be published'
        USING ERRCODE = 'check_violation';
    END IF;
    SELECT "version", "visibility" INTO l FROM "ProductSiteListing" WHERE "id" = NEW."listingId";
    IF l."visibility" IS DISTINCT FROM 'VISIBLE' OR l."version" IS DISTINCT FROM NEW."listingVersion" THEN
      RAISE EXCEPTION 'catalog: only the current visible listing can be published'
        USING ERRCODE = 'check_violation';
    END IF;
  END IF;
  RETURN NEW;
END
$fn$;
CREATE TRIGGER "ProductPublication_guard" BEFORE INSERT OR UPDATE ON "ProductPublication"
  FOR EACH ROW EXECUTE FUNCTION catalog_publication_guard();

-- An image shown by a live publication cannot be deleted (the public site would lose it).
CREATE FUNCTION catalog_image_published_guard() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF EXISTS (
    SELECT 1 FROM "ProductPublication" p
    WHERE p."productId" = OLD."productId" AND p."status" = 'PUBLISHED' AND OLD."id" = ANY (p."imageIds")
  ) THEN
    RAISE EXCEPTION 'catalog: a published image cannot be deleted'
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN OLD;
END
$fn$;
CREATE TRIGGER "ProductImage_published_guard" BEFORE DELETE ON "ProductImage"
  FOR EACH ROW EXECUTE FUNCTION catalog_image_published_guard();

