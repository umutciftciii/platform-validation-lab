-- The status machine of a product master, enforced for every writer:
--  * a content change (version bump without a status change) while IN_REVIEW or APPROVED
--    returns the master to DRAFT: an approval never silently covers later edits;
--  * only these transitions exist: DRAFT->IN_REVIEW, IN_REVIEW->DRAFT, IN_REVIEW->APPROVED,
--    APPROVED->DRAFT, any->ARCHIVED, ARCHIVED->DRAFT;
--  * approval: the approver is recorded, is neither the submitter nor anyone who changed the
--    content since the last approval (separation of duties), and the revision editors restart;
--  * archiving is refused while the product is published on any site.
CREATE FUNCTION catalog_product_workflow_guard() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF NEW."version" <> OLD."version" AND NEW."status" = OLD."status"
     AND OLD."status" IN ('IN_REVIEW', 'APPROVED') THEN
    NEW."status" := 'DRAFT';
  END IF;
  IF NEW."status" = OLD."status" THEN
    RETURN NEW;
  END IF;
  IF NOT (
       (OLD."status" = 'DRAFT' AND NEW."status" = 'IN_REVIEW')
    OR (OLD."status" = 'IN_REVIEW' AND NEW."status" IN ('DRAFT', 'APPROVED'))
    OR (OLD."status" = 'APPROVED' AND NEW."status" = 'DRAFT')
    OR (NEW."status" = 'ARCHIVED')
    OR (OLD."status" = 'ARCHIVED' AND NEW."status" = 'DRAFT')
  ) THEN
    RAISE EXCEPTION 'catalog: product status cannot change from % to %', OLD."status", NEW."status"
      USING ERRCODE = 'check_violation';
  END IF;
  IF NEW."status" = 'APPROVED' THEN
    IF NEW."approvedById" IS NULL
       OR NEW."approvedById" IS NOT DISTINCT FROM OLD."submittedById"
       OR NEW."approvedById" = ANY (OLD."revisionEditorIds") THEN
      RAISE EXCEPTION 'catalog: separation of duties: the approver changed or submitted this revision'
        USING ERRCODE = 'check_violation';
    END IF;
    NEW."revisionEditorIds" := ARRAY[]::uuid[];
  END IF;
  IF NEW."status" = 'ARCHIVED' AND EXISTS (
    SELECT 1 FROM "ProductPublication" p WHERE p."productId" = NEW."id" AND p."status" = 'PUBLISHED'
  ) THEN
    RAISE EXCEPTION 'catalog: a published product cannot be archived'
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END
$fn$;
CREATE TRIGGER "Product_workflow_guard" BEFORE UPDATE ON "Product"
  FOR EACH ROW EXECUTE FUNCTION catalog_product_workflow_guard();

-- Review decisions come from someone outside the revision (separation of duties), checked
-- against the master as it is when the event is written (before the status change).
CREATE FUNCTION catalog_review_event_guard() RETURNS trigger LANGUAGE plpgsql AS $fn$
DECLARE
  p RECORD;
BEGIN
  IF NEW."action" IN ('APPROVED', 'CHANGES_REQUESTED') THEN
    SELECT "status", "submittedById", "revisionEditorIds" INTO p
      FROM "Product" WHERE "id" = NEW."productId";
    IF p."status" IS DISTINCT FROM 'IN_REVIEW' THEN
      RAISE EXCEPTION 'catalog: a review decision needs a product in review'
        USING ERRCODE = 'check_violation';
    END IF;
    IF NEW."actorUserId" IS NOT DISTINCT FROM p."submittedById"
       OR NEW."actorUserId" = ANY (p."revisionEditorIds") THEN
      RAISE EXCEPTION 'catalog: separation of duties: the reviewer changed or submitted this revision'
        USING ERRCODE = 'check_violation';
    END IF;
  END IF;
  RETURN NEW;
END
$fn$;
CREATE TRIGGER "ProductReviewEvent_guard" BEFORE INSERT ON "ProductReviewEvent"
  FOR EACH ROW EXECUTE FUNCTION catalog_review_event_guard();

-- The review history is append-only, for every role (the privileges below are the first line).
CREATE FUNCTION catalog_review_event_append_only() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  RAISE EXCEPTION 'catalog: the review history is append-only'
    USING ERRCODE = 'insufficient_privilege';
END
$fn$;
CREATE TRIGGER "ProductReviewEvent_append_only" BEFORE UPDATE OR DELETE ON "ProductReviewEvent"
