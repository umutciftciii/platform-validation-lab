  ADD CONSTRAINT "Product_submitted_consistent" CHECK (
    ("submittedAt" IS NULL) = ("submittedById" IS NULL)
    AND ("submittedAt" IS NULL) = ("submittedVersion" IS NULL)),
  ADD CONSTRAINT "Product_approved_consistent" CHECK (
    ("approvedAt" IS NULL) = ("approvedById" IS NULL)
    AND ("approvedAt" IS NULL) = ("approvedVersion" IS NULL)),
  ADD CONSTRAINT "Product_in_review_submitted" CHECK (
    "status" <> 'IN_REVIEW' OR "submittedVersion" = "version"),
  ADD CONSTRAINT "Product_approved_current" CHECK (
    "status" <> 'APPROVED' OR "approvedVersion" = "version");

ALTER TABLE "ProductReviewEvent"
