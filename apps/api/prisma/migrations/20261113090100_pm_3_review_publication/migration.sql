-- ===========================================================================================
-- Part 4: back-fill the revision editors of existing masters from the audit trail
-- ===========================================================================================

-- Everyone who created or changed a master's content (master fields, specification values,
-- images) before PM-3 counts as an editor of its current revision, so none of them can approve
-- it. Archived products are included (they return to DRAFT when restored). The version and the
-- status are unchanged, so the workflow trigger does nothing here.
UPDATE "Product" p
SET "revisionEditorIds" = e.ids
FROM (
  SELECT x."productId", array_agg(DISTINCT x."actorUserId" ORDER BY x."actorUserId") AS ids
  FROM (
    SELECT a."resourceId" AS "productId", a."actorUserId"
    FROM "AuditEvent" a
    WHERE a."outcome" = 'SUCCESS' AND a."actorUserId" IS NOT NULL AND a."resourceType" = 'product'
      AND a."action" IN ('catalog.product_created', 'catalog.product_updated',
                         'catalog.spec_values_saved', 'catalog.images_reordered')
    UNION ALL
    SELECT a."metadata" ->> 'productId', a."actorUserId"
    FROM "AuditEvent" a
    WHERE a."outcome" = 'SUCCESS' AND a."actorUserId" IS NOT NULL AND a."resourceType" = 'product_image'
      AND a."action" IN ('catalog.image_uploaded', 'catalog.image_updated',
                         'catalog.image_cover_set', 'catalog.image_deleted')
  ) x
  WHERE x."productId" ~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
  GROUP BY x."productId"
) e
WHERE p."id" = e."productId"::uuid;
